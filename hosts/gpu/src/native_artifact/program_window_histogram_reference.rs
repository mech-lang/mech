//! Test-only frozen pre-unrolling emitter; no production fallback/executor.
use super::*;

pub(super) fn emit(b: &mut FunctionBuilder<'_>) {
    let entry = b.create_block();
    let empty = b.create_block();
    let outer = b.create_block();
    let pair = b.create_block();
    let increment = b.create_block();
    let done = b.create_block();
    b.append_block_params_for_function_params(entry);
    b.append_block_param(outer, types::I64);
    b.append_block_param(increment, types::I64);
    b.switch_to_block(entry);
    let args = b.block_params(entry).to_vec();
    let (source, length, bins, width) = (args[0], args[1], args[2], args[4]);
    let zero = b.ins().iconst(types::I64, 0);
    let positive = b.ins().icmp_imm(IntCC::NotEqual, width, 0);
    let fits = b.ins().icmp(IntCC::UnsignedLessThanOrEqual, width, length);
    let valid = b.ins().band(positive, fits);
    b.ins().brif(valid, outer, &[zero.into()], empty, &[]);
    b.switch_to_block(empty);
    b.ins().return_(&[zero]);
    b.switch_to_block(outer);
    let offset = b.block_params(outer)[0];
    let address = b.ins().iadd(source, offset);
    let byte = b.ins().load(types::I8, MemFlags::new(), address, 0);
    let first = b.ins().uextend(types::I64, byte);
    let one = b.ins().icmp_imm(IntCC::Equal, width, 1);
    b.ins().brif(one, increment, &[first.into()], pair, &[]);
    b.switch_to_block(pair);
    let byte = b.ins().load(types::I8, MemFlags::new(), address, 1);
    let second = b.ins().uextend(types::I64, byte);
    let high = b.ins().ishl_imm(first, 7);
    let key = b.ins().bor(high, second);
    b.ins().jump(increment, &[key.into()]);
    b.switch_to_block(increment);
    let key = b.block_params(increment)[0];
    let byte_offset = b.ins().ishl_imm(key, 3);
    let cell = b.ins().iadd(bins, byte_offset);
    let old = b.ins().load(types::I64, MemFlags::new(), cell, 0);
    let count = b.ins().iadd_imm(old, 1);
    b.ins().store(MemFlags::new(), count, cell, 0);
    let last = b.ins().isub(length, width);
    let more = b.ins().icmp(IntCC::UnsignedLessThan, offset, last);
    let next = b.ins().iadd_imm(offset, 1);
    b.ins().brif(more, outer, &[next.into()], done, &[]);
    b.switch_to_block(done);
    b.ins().return_(&[next]);
}
