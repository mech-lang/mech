const assert=require('node:assert/strict');
const fs=require('node:fs');
const {pathToFileURL}=require('node:url');
const data=JSON.parse(fs.readFileSync(__dirname+'/dist/data.json','utf8'));
const click=(page,selector)=>page.evaluate(selector=>document.querySelector(selector).click(),selector);
const read=page=>page.evaluate(()=>window.benchmarkExplorer.getSelection());
const option=(dimension,key)=>`[data-trait-option="${dimension}:${key}"]`;
const sorted=values=>[...values].sort();
(async()=>{
  const module=await import(process.env.PLAYWRIGHT_MODULE?pathToFileURL(require.resolve(process.env.PLAYWRIGHT_MODULE)).href:'playwright');
  const {chromium}=module.default??module;
  const browser=await chromium.launch({executablePath:process.env.BROWSER_EXECUTABLE||'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
  const errors=[],checks=[];
  try{
    for(const width of [1440,390,320]){
      const page=await browser.newPage({viewport:{width,height:1000},colorScheme:'dark'});
      page.on('pageerror',error=>errors.push(error.message));
      await page.goto(process.env.BENCHMARK_EXPLORER_URL||'http://127.0.0.1:8766/');
      await page.waitForFunction(()=>window.benchmarkExplorer);
      const baseline=await read(page),bounds=await page.evaluate(()=>window.benchmarkExplorer.getDomains());
      const chartTop=await page.locator('#chart').evaluate(element=>element.getBoundingClientRect().top+scrollY);
      await click(page,option('style','array'));
      await click(page,option('typing','dynamic'));
      const array=data.language_groups.find(group=>group.key==='array').languages;
      const dynamic=data.language_groups.find(group=>group.key==='dynamic').languages;
      const expected=array.filter(key=>dynamic.includes(key));
      let state=await read(page);
      assert.deepEqual(sorted(state.languages),sorted(expected));
      assert(!state.languages.includes('javascript')&&!state.languages.includes('lisp'));
      assert.deepEqual(state.benchmarks,baseline.benchmarks);
      assert.deepEqual(await page.evaluate(()=>window.benchmarkExplorer.getDomains()),bounds);
      assert.equal(await page.locator('[data-only-group]').count(),0);
      assert.deepEqual(sorted(await page.locator('input[data-language]:not(:disabled)').evaluateAll(nodes=>nodes.map(node=>node.dataset.language))),sorted(expected));
      assert.equal(await page.locator(option('style','array')).isChecked(),true);
      assert.equal(await page.locator(option('typing','dynamic')).isChecked(),true);
      assert.equal(await page.locator('#chart').evaluate(element=>element.getBoundingClientRect().top+scrollY),chartTop,'Filtering does not shift the chart');
      await page.screenshot({path:__dirname+`/trait-array-dynamic-${width}.png`,fullPage:false});
      await click(page,option('memory','rc'));
      assert.deepEqual(sorted((await read(page)).languages),sorted(['bqn','k','uiua'].filter(key=>expected.includes(key))));
      await click(page,option('memory','rc'));
      await click(page,'[data-view="benchmark"]');
      assert.deepEqual(sorted((await read(page)).languages),sorted(expected));
      assert.equal(await page.locator('[data-chart-language="javascript"]').count(),0);
      await click(page,'[data-view="summary"]');
      await click(page,option('execution','jit'));
      const jit=await read(page);
      assert(jit.languages.every(key=>expected.includes(key)));
      assert(jit.languages.includes('julia'));
      assert(!jit.languages.includes('mech-jit'));
      await click(page,option('execution','aot'));
      assert((await read(page)).languages.includes('julia'),'Adding AOT does not discard JIT choice');
      await click(page,option('typing','static'));
      state=await read(page);
      assert(state.languages.includes('mech')&&state.languages.includes('mech-jit'));
      assert(!state.languages.includes('mech-resident'));
      await click(page,'[data-language="mech-jit"]');
      await click(page,'#clear-traits');
      state=await read(page);
      assert(!state.languages.includes('mech-jit'),'Clearing filters preserves manual exclusions');
      assert(state.languages.includes('javascript'));
      await click(page,'#all-languages');
      await click(page,option('execution','interpreted'));
      await click(page,'[data-view="mech"]');
      state=await read(page);
      assert.deepEqual(sorted(state.languages.filter(key=>key.startsWith('mech'))),['mech','mech-jit','mech-resident']);
      assert(Object.values(state.traits).every(values=>values.length===0));
      assert.equal(state.samples,true);
      await click(page,'#no-languages');
      state=await read(page);
      assert.deepEqual(state.languages,[]);
      await click(page,'#all-languages');
      assert.equal((await read(page)).languages.length,data.languages.length);
      await page.locator('#focus-means').check(); // Mech view deliberately defaults to the full sample range.
      assert.deepEqual(await page.evaluate(()=>window.benchmarkExplorer.getDomains()),bounds);
      const overflow=await page.locator('.controls').evaluate(element=>element.scrollWidth>element.clientWidth+1);
      assert.equal(overflow,false,`No filter overflow at ${width}px`);
      checks.push({width,intersection:true,within_category_alternatives:true,fixed_axes:true,manual_selection:true,mech_modes:true});
      await page.screenshot({path:__dirname+`/trait-filters-${width}.png`,fullPage:false});
      await page.close();
    }
    assert.deepEqual(errors,[]);
    fs.writeFileSync(__dirname+'/trait-filters-ui-checks.json',JSON.stringify({passed:true,checks,errors},null,2)+'\n');
    console.log(JSON.stringify({passed:true,checks}));
  }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
