import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { RobotScene } from './drawing.mjs';

const root = dirname(fileURLToPath(import.meta.url));
const repo = resolve(root, '../../..');
const turns = 40;

export async function buildHero(destination = join(root, 'hero.svg')) {
  const source = readFileSync(join(root, 'source/ekf.mec'), 'utf8');
  const sourceHash = createHash('sha256').update(source).digest('hex');
  assert.equal(sourceHash, 'f18e37effb2fa63fadca69639f3a8eed218b73218decf65419e78a60b62bb46b');
  const runtime = await import(pathToFileURL(join(repo, 'src/wasm/pkg/mech_wasm.js')));
  await runtime.default({ module_or_path: readFileSync(join(repo, 'src/wasm/pkg/mech_wasm_bg.wasm')) });
  const kernel = runtime.WasmKernel.fromSource(source, {
    bearing: new Float32Array([-0.55]), v: [1], w: [0.015],
  }, ['μ', 'Σ']);
  const simulation = { truth: [55, 25, 0.4], turn: 0 };
  const trail = [[55, 25]];
  let state, covariance;
  try {
    for (let turn = 0; turn < turns; turn++) {
      // Invoke the demo's sensor source itself; estimated values come only
      // from the checked Mech kernel, never from a JavaScript EKF.
      const observation = RobotScene.prototype.observation.call(simulation, 1, 0.015, 0.02, 1);
      kernel.turn(observation.inputs);
      simulation.truth = observation.next;
      simulation.turn++;
      state = Array.from(kernel.stateSample('μ', 0));
      const columnMajor = kernel.stateSample('Σ', 0);
      covariance = [columnMajor[0], columnMajor[3], columnMajor[6], columnMajor[1], columnMajor[4], columnMajor[7], columnMajor[2], columnMajor[5], columnMajor[8]];
      trail.push(state.slice(0, 2));
    }
  } finally {
    kernel.free();
  }
  assert(state.every(Number.isFinite) && covariance.every(Number.isFinite));
  const pxx = covariance[0], pxy = (covariance[1] + covariance[3]) / 2, pyy = covariance[4];
  const separation = Math.hypot(pxx - pyy, 2 * pxy);
  const major = 2 * Math.sqrt((pxx + pyy + separation) / 2);
  const minor = 2 * Math.sqrt((pxx + pyy - separation) / 2);
  assert(major > 0 && minor > 0, 'a finite positive position covariance is required');
  const angle = -Math.atan2(2 * pxy, pxx - pyy) * 90 / Math.PI;
  const X = x => 70 + (x - 20) * 5;
  const Y = y => 510 - (y + 5) * 5;
  const number = value => Number(value.toFixed(3));
  const cx = X(state[0]), cy = Y(state[1]);
  const grid = [];
  for (const x of [40, 60, 80, 100, 120, 140]) grid.push(`<path d="M${X(x)} 130V510"/>`);
  for (const y of [0, 20, 40, 60]) grid.push(`<path d="M70 ${Y(y)}H740"/>`);
  const ticks = [40, 80, 120].map(x => `<text x="${X(x)}" y="532" text-anchor="middle">${x}</text>`).join('');
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="800" height="640" viewBox="0 0 800 640" role="img" aria-labelledby="hero-title hero-desc">
<title id="hero-title">A bearing-only EKF after ${turns} checked Mech turns</title>
<desc id="hero-desc">Generated by the actual Mech v0.4 WebAssembly kernel from source SHA-256 ${sourceHash}. Forty steps of 0.1 seconds use the live demo's deterministic sensor source, velocity 1, angular velocity 0.015, and noise scale 0.02. Estimated pose is ${state.map(number).join(', ')}. The purple ellipse uses the position covariance eigenvectors and two times the square roots of its eigenvalues; it is not a 95 percent confidence region. Landmark coordinates are 140, 12. JavaScript supplies sensor observations and draws these computed values.</desc>
<rect width="800" height="640" rx="12" fill="#0b1012"/>
<rect x="0.5" y="0.5" width="799" height="639" rx="12" fill="none" stroke="#35393d"/>
<g font-family="Inter,system-ui,sans-serif">
<text x="38" y="49" fill="#f2b63d" font-size="14" letter-spacing="2.1">BEARING-ONLY EKF</text>
<circle cx="606" cy="43" r="4" fill="#62b4a4"/>
<text x="620" y="48" fill="#91cabc" font-size="13">${turns} checked turns</text>
<path d="M38 74H762" stroke="#35393d"/>
<g fill="none" stroke="#1d292f" stroke-width="1">${grid.join('')}</g>
<path d="M70 130V510H740" fill="none" stroke="#4d5257" stroke-width="1.2"/>
<g fill="#778b94" font-size="12">${ticks}<text x="50" y="389" text-anchor="end">20</text><text x="50" y="289" text-anchor="end">40</text><text x="50" y="189" text-anchor="end">60</text><text x="70" y="114">y</text><text x="740" y="546" text-anchor="end">x · world coordinates</text></g>
<path d="M${number(cx)} ${number(cy)}L${X(140)} ${Y(12)}" stroke="#62b4a4" stroke-width="1.4" stroke-dasharray="5 7"/>
<ellipse cx="${number(cx)}" cy="${number(cy)}" rx="${number(major * 5)}" ry="${number(minor * 5)}" transform="rotate(${number(angle)} ${number(cx)} ${number(cy)})" fill="#bc8cbf" fill-opacity="0.13" stroke="#bc8cbf" stroke-width="1.8"/>
<polyline points="${trail.map(([x, y]) => `${number(X(x))},${number(Y(y))}`).join(' ')}" fill="none" stroke="#f2b63d" stroke-width="2"/>
<circle cx="${X(55)}" cy="${Y(25)}" r="3" fill="#0b1012" stroke="#b1bfc6" stroke-width="1.2"/>
<g transform="translate(${number(cx)} ${number(cy)}) rotate(${number(-state[2] * 180 / Math.PI)})"><circle r="17" fill="#0b1012" stroke="#f2b63d" stroke-width="1.5"/><path d="M-7 -7L12 0L-7 7L-3 0Z" fill="#f2b63d"/></g>
<text x="${number(cx + 27)}" y="${number(cy - 25)}" fill="#f5ddaa" font-size="15">estimated pose</text>
<path d="M${number(cx - 70)} ${number(cy - 78)}L${number(cx - 46)} ${number(cy - 52)}" fill="none" stroke="#bc8cbf"/>
<text x="${number(cx - 77)}" y="${number(cy - 92)}" text-anchor="middle" fill="#d4aed6" font-size="14">2σ position ellipse</text>
<circle cx="${X(140)}" cy="${Y(12)}" r="7" fill="#62b4a4"/>
<circle cx="${X(140)}" cy="${Y(12)}" r="15" fill="none" stroke="#62b4a4" stroke-opacity="0.45"/>
<text x="${X(140) - 2}" y="${Y(12) - 39}" text-anchor="middle" fill="#91cabc" font-size="15">landmark</text>
<text x="${X(140) - 2}" y="${Y(12) - 20}" text-anchor="middle" fill="#778b94" font-size="12">(140, 12)</text>
<text x="468" y="366" fill="#91cabc" font-size="12" transform="rotate(10 468 366)">bearing observation</text>
<path d="M38 574H762" stroke="#35393d"/>
<text x="38" y="608" fill="#d6e0e5" font-family="'Fira Code',monospace" font-size="14">μ = [${state.map(value => value.toFixed(3)).join(', ')}]</text>
<text x="762" y="608" text-anchor="end" fill="#778b94" font-size="13">4.0 s simulated</text>
</g>
</svg>
`;
  writeFileSync(destination, svg);
  return { turns, state, covariance, major, minor, angle, sourceHash, destination };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(JSON.stringify(await buildHero(process.argv[2] && resolve(process.argv[2])), null, 2));
}
